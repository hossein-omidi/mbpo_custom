#!/usr/bin/env bash
# Optional curriculum runner: Stages 0→3 with reduced epoch budgets.
# Each stage calls mbpo run_local WITHOUT --restore (independent trials).
# For gate-ready Stage 0/1 runs, use docs/TRAINING_PROTOCOL.md §0 + full configs.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_DIR="$ROOT/examples/config/pv_tracking"
RAY_ROOT="${RAY_ROOT:-$HOME/ray_mbpo/PVTracking/pv_tracking}"
ARTIFACT_DIR="$ROOT/sequential_stage_artifacts"
EVAL_ROOT="$ROOT/evaluation"

CONDA_SH="${CONDA_SH:-$HOME/miniconda3/etc/profile.d/conda.sh}"
CONDA_ENV_NAME="${CONDA_ENV_NAME:-mbpo}"

CPUS="${CPUS:-4}"
TRIAL_CPUS="${TRIAL_CPUS:-2}"
GPUS="${GPUS:-0}"
TRIAL_GPUS="${TRIAL_GPUS:-0}"
EVAL_ROLLOUTS="${EVAL_ROLLOUTS:-8}"
MAX_PATH_LENGTH="${MAX_PATH_LENGTH:-39}"
STOP_ON_GATE_FAIL="${STOP_ON_GATE_FAIL:-0}"
STAGE3_VALIDATION_DATES="2020-02-15,2020-05-15,2020-08-15,2020-11-15"

mkdir -p "$ARTIFACT_DIR"
mkdir -p "$EVAL_ROOT"

if [[ ! -f "$CONDA_SH" ]]; then
  echo "Missing conda init script: $CONDA_SH" >&2
  exit 1
fi

# shellcheck disable=SC1090
source "$CONDA_SH"
conda activate "$CONDA_ENV_NAME"
cd "$ROOT"

