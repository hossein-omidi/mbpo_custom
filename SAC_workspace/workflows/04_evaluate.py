"""Paired photovoltaic evaluation vs dual-axis tracking on NSRDB days."""
import argparse
from pathlib import Path
from SAC_workspace.src.config.config import load_config
from SAC_workspace.src.evaluation.evaluation import evaluate, write_outputs
from SAC_workspace.src.evaluation.plots import plot_results


def main():
    ap=argparse.ArgumentParser(description='Evaluate trained SAC on matched NSRDB scenarios')
    ap.add_argument('--checkpoint', required=True, help='Trusted latest.pt generated by SAC workspace')
    ap.add_argument('--outdir', default='SAC_workspace/evaluation')
    ap.add_argument('--seeds', type=int, nargs='+', default=[42])
    from SAC_workspace.src.evaluation.scenario_sampling import add_selection_arguments
    add_selection_arguments(ap)
    ap.add_argument('--device', default='cpu')
    ap.add_argument('--training-csv', default=None)
    args=ap.parse_args()
    cfg=load_config()
    from mbpo.env.nsrdb_weather import load_scenario_manifest
    from SAC_workspace.src.evaluation.scenario_sampling import resolve_cli_selection,save_selection
    manifest = load_scenario_manifest(cfg.manifest)
    try:
        scenario_ids,plan=resolve_cli_selection(args,manifest,training_csvs=([args.training_csv] if args.training_csv else []))
    except ValueError as exc:
        ap.error(str(exc))
    if plan is not None:
        save_selection(plan,args.outdir)
        print(f'Selected {plan["selected_count"]} of {plan["population_count"]} NSRDB days '
              f'from {plan["year_month_strata_count"]} year-month groups, protocol={plan["protocol"]}')
    paths=evaluate(cfg,args.checkpoint,scenario_ids=scenario_ids,seeds=args.seeds,device=args.device)
    stats=write_outputs(paths,args.outdir)
    plot_results(paths,args.outdir,args.training_csv)
    if plan is not None:
        from SAC_workspace.src.evaluation.stratified_statistics import render_statistical_report
        report=render_statistical_report(Path(args.outdir)/'stratified',plan,paths=paths)
        print('Stratified year/month/season/movement report:',Path(args.outdir,'stratified').resolve(),
              '| figures:',len(report['figures']))
    for name, row in stats['methods'].items():
        print(f"{name:26s} net={row['mean_net_kwh']} gross={row['mean_gross_kwh']:.6f} kWh")
    print('Paired confidence intervals, CSV and figures:',Path(args.outdir).resolve())

if __name__ == '__main__': main()
